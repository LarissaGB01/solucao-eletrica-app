// Inlines KaTeX JS, CSS and woff2 fonts into a TS module so formulas render offline (ADR 0004).
// Runs on postinstall; the output is gitignored.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const katexDist = dirname(require.resolve('katex/dist/katex.min.js'));
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const output = join(
  root,
  'src/presentation/ui/Formula/katexAssets.generated.ts',
);

const fontDataUri = file =>
  `data:font/woff2;base64,${readFileSync(
    join(katexDist, 'fonts', file),
  ).toString('base64')}`;

// Keep only the woff2 source of each @font-face and inline it.
const css = readFileSync(join(katexDist, 'katex.min.css'), 'utf8').replace(
  /src:url\(fonts\/([^)]+\.woff2)\) format\("woff2"\)[^;}]*/g,
  (_, file) => `src:url(${fontDataUri(file)}) format("woff2")`,
);
if (css.includes('url(fonts/')) {
  throw new Error(
    'Unexpected KaTeX font declaration; update build-katex-assets.mjs',
  );
}

const js = readFileSync(join(katexDist, 'katex.min.js'), 'utf8').replace(
  /<\/script/gi,
  '<\\/script',
);

writeFileSync(
  output,
  `// Generated by scripts/build-katex-assets.mjs. Do not edit.\n` +
    `export const KATEX_CSS = ${JSON.stringify(css)};\n` +
    `export const KATEX_JS = ${JSON.stringify(js)};\n`,
);
console.log(
  `KaTeX assets written to ${output} (${Math.round(
    (css.length + js.length) / 1024,
  )} KB)`,
);
